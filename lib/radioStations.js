export function getAllStations() {
  const allStations = [];
  Object.entries(radioStations).forEach(([countryCode, countryData]) => {
    countryData.stations.forEach((station) => {
      allStations.push({
        ...station,
        country: countryData.name,
        countryCode,
        flag: countryData.flag,
      });
    });
  });
  return allStations;
}

export function searchStations(query) {
  const lowerQuery = query.toLowerCase();
  return getAllStations().filter(
    (station) =>
      station.name.toLowerCase().includes(lowerQuery) ||
      station.genre.toLowerCase().includes(lowerQuery) ||
      station.country.toLowerCase().includes(lowerQuery) ||
      station.description.toLowerCase().includes(lowerQuery)
  );
}

export function getStationsByCountry(countryCode) {
  return (
    radioStations[countryCode]?.stations.map((station) => ({
      ...station,
      country: radioStations[countryCode].name,
      countryCode,
      flag: radioStations[countryCode].flag,
    })) || []
  );
}

export function getRandomStations(count = 10) {
  const all = getAllStations();
  const shuffled = all.sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
